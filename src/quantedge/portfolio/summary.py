"""One-page return-objective summary (D12), rebuilt from the output tables on every run so its numbers
always match outputs/tables/ and update when the config values change."""
from __future__ import annotations

from pathlib import Path

import pandas as pd


def _pct(x: float, dp: int = 2) -> str:
    return f"{x * 100:.{dp}f}%"


def write_return_objective_summary(path: Path, *, as_of, inflation: float, rf: float, mandate: dict,
                                   erp_base: float, erp_own: dict, grid: pd.DataFrame, vs: pd.DataFrame,
                                   assets: pd.DataFrame) -> None:
    s, g, c = (mandate[k]["base"] for k in ("spending_rate", "real_growth", "extra_costs"))
    req = vs["required_gross"].iloc[0]
    erp_label = f"{erp_base:.0%}"
    rf_base, tax_base = vs["rf_scenario"].iloc[0], "tax-exempt (base)"
    core = vs[(vs["rf_scenario"] == rf_base) & (vs["tax_case"] == tax_base)]
    base = core[core["erp"] == erp_label].set_index("portfolio")
    erp_cols = [e for e in vs["erp"].unique() if e != "own data"]
    by_erp = core.pivot_table(index="portfolio", columns="erp", values="expected_geometric")
    at_erp = vs[(vs["erp"] == erp_label) & (vs["tax_case"] == tax_base)]
    by_rf = at_erp.pivot_table(index="portfolio", columns="rf_scenario", values="expected_geometric")
    sp_rf = at_erp.pivot_table(index="portfolio", columns="rf_scenario", values="sustainable_spending")
    rf_cols = list(vs["rf_scenario"].unique())
    taxed = vs[(vs["erp"] == erp_label) & (vs["rf_scenario"] == rf_base) & (vs["tax_case"] != tax_base)]

    L = [f"# Return Objective: One-Page Summary (D12)",
         f"*As of {as_of}. Generated by `python run_all.py --only portfolio`. Values provisional (team, 2026-10-28).*",
         "",
         "## 1. What the endowment needs",
         f"Required return = (1 + inflation)(1 + spending)(1 + real growth)(1 + costs) − 1 = "
         f"(1 + {_pct(inflation)})(1 + {_pct(s)})(1 + {_pct(g)})(1 + {_pct(c)}) − 1 = **{_pct(req)} per year**",
         "",
         "| Input | Value | Basis |", "|---|---|---|",
         f"| Inflation | {_pct(inflation)} | FRED 10-year breakeven (market's expected US inflation); spending assumed in USD |",
         f"| Spending | {_pct(s)} | Scholarships, research and other university needs |",
         f"| Real growth | {_pct(g)} | Grow purchasing power slightly above inflation |",
         f"| Extra costs | {_pct(c)} | Management and trading costs not already inside ETF prices |",
         "",
         "## 2. What portfolios can realistically earn",
         f"Expected compound return = CAPM (risk-free {_pct(rf)} + β × equity risk premium {erp_label}) − ½ variance "
         f"(daily-return covariance). "
         f"Reference portfolios only; the optimised candidates come in the portfolio stage.",
         "",
         "| Portfolio | Expected return | Volatility | Gap vs need | Meets need? | **Spending it can support** |",
         "|---|---|---|---|---|---|"]
    for name, r in base.sort_values("expected_geometric").iterrows():
        L.append(f"| {name} | {_pct(r.expected_geometric)} | {_pct(r.volatility, 1)} | {_pct(r.gap)} | "
                 f"{'Yes' if r.meets_requirement else 'No'} | **{_pct(r.sustainable_spending)}** |")
    weakest, strongest = base["sustainable_spending"].idxmin(), base["sustainable_spending"].idxmax()
    short = base[~base["meets_requirement"]]
    L += ["",
          "## 3. What this means for the committee",
          (f"- {len(short)} of {len(base)} reference portfolios fall short of the {_pct(req)} requirement at a {erp_label} equity premium."
           if len(short) else f"- All reference portfolios meet the {_pct(req)} requirement at a {erp_label} equity premium."),
          f"- **Agreed shortfall policy: lower spending, not more risk.** The most defensive mix ({weakest}) supports about "
          f"**{_pct(base.loc[weakest, 'sustainable_spending'])} spending** instead of {_pct(s)}; "
          f"{strongest} supports about {_pct(base.loc[strongest, 'sustainable_spending'])}, but with "
          f"{_pct(base.loc[strongest, 'volatility'], 1)} volatility.",
          f"- \"Spending it can support\" keeps inflation protection, {_pct(g)} real growth and {_pct(c)} costs, "
          "and solves for the spending rate that makes expected return equal to the requirement.",
          "",
          "## 4. How sensitive is this?",
          "Expected return at different equity risk premiums (columns) vs requirement " + _pct(req) + ":",
          "",
          "| Portfolio | " + " | ".join(f"ERP {e}" for e in erp_cols) + " |",
          "|---|" + "---|" * len(erp_cols)]
    for name in base.sort_values("expected_geometric").index:
        L.append(f"| {name} | " + " | ".join(_pct(by_erp.loc[name, e]) for e in erp_cols) + " |")
    req_tbl = grid[grid["costs"] == c].pivot_table(index="spending", columns="real_growth", values="required_gross")
    L += ["",
          f"Expected return if the risk-free rate falls over the 5-year horizon (ERP {erp_label}); spending supported in brackets:",
          "",
          "| Portfolio | " + " | ".join(f"rf {r}" for r in rf_cols) + " |",
          "|---|" + "---|" * len(rf_cols)]
    for name in base.sort_values("expected_geometric").index:
        L.append(f"| {name} | " + " | ".join(f"{_pct(by_rf.loc[name, r])} ({_pct(sp_rf.loc[name, r], 1)})" for r in rf_cols) + " |")
    L += ["",
          "Required return by spending (rows) and real growth (columns), costs " + _pct(c) + ": " +
          "; ".join(f"S {_pct(si, 1)} → " + " / ".join(_pct(req_tbl.loc[si, gi]) for gi in req_tbl.columns)
                    for si in req_tbl.index) +
          f" (growth {' / '.join(_pct(gi, 1) for gi in req_tbl.columns)}).",
          "",
          "## 5. Caveats",
          f"- Own-data equity premium is {_pct(erp_own['erp_arithmetic'], 1)} (95% CI {_pct(erp_own['ci95_low'], 1)}–"
          f"{_pct(erp_own['ci95_high'], 1)}). 2004–2026 was unusually strong for US stocks, so a {erp_label} base is used.",
          f"- CAPM gives gold about {_pct(assets.loc['GLD', f'capm_E[R] erp {erp_label}'], 1)} (β ≈ 0) against "
          f"{_pct(assets.loc['GLD', 'hist_geometric'], 1)} historically; it ignores gold's role as an inflation and crisis hedge.",
          f"- Base case uses today's T-bill ({_pct(rf)}). If short rates average less over 5 years, every CAPM expected return "
          "falls one-for-one (table above). AGG's real sensitivity is smaller because its current yield is locked in for its ~6-year duration.",
          "- Tax-exempt base case. Withholding is applied per ETF on each fund's own distribution yield: "
          + "; ".join(f"{case}: −{_pct(taxed[taxed.tax_case == case]['withholding_drag'].min())} to "
                      f"−{_pct(taxed[taxed.tax_case == case]['withholding_drag'].max())}" for case in taxed["tax_case"].unique()) + ".",
          "- Variance drag uses daily-return covariance (60/40: ~11.5% volatility). Monthly data gives lower volatility (~9.4%) "
          "and would flatter compound returns; monthly figures are reported for information only.",
          "- Gold's protective value is assessed separately (research doc §7), not through CAPM.",
          "- Expected returns are estimates with wide uncertainty; the risk stage tests downside, which matters more for this client."]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
